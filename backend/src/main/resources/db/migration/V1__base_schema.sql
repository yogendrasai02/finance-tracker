    user_id                 BIGINT NOT NULL,
    account_id              BIGINT NOT NULL,
    as_of_date              DATE NOT NULL,
    actual_balance_paise    BIGINT NOT NULL,
    note                    TEXT,
    created_at              TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at              TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT pk_balance_checkpoints PRIMARY KEY (id),
    CONSTRAINT ux_balance_checkpoints_account_date UNIQUE (user_id, account_id, as_of_date),
    CONSTRAINT fk_balance_checkpoints_user FOREIGN KEY (user_id) REFERENCES app.users (id) ON DELETE RESTRICT,
    CONSTRAINT fk_balance_checkpoints_account FOREIGN KEY (user_id, account_id) REFERENCES app.accounts (user_id, id) ON DELETE RESTRICT
);

CREATE INDEX ix_transactions_user_txn_date
    ON app.transactions (user_id, txn_date);

CREATE INDEX ix_transactions_account_txn_date_id
    ON app.transactions (account_id, txn_date, id);

CREATE INDEX ix_transactions_statement_import_id
    ON app.transactions (statement_import_id)
    WHERE statement_import_id IS NOT NULL;

CREATE UNIQUE INDEX ux_statement_imports_cc_statement
    ON app.statement_imports (user_id, account_id, statement_date)
    WHERE status = 'COMMITTED' AND statement_date IS NOT NULL;

